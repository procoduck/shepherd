package merge_test

import (
	"strings"
	"testing"

	"shepherd/internal/merge"
)

// Native Go fuzz targets for the #297 line attribution. Plain `go test` runs
// only the seed corpus (the f.Add calls plus testdata/fuzz/<Name>/); fuzz
// with e.g. `go test -run='^$' -fuzz=FuzzAssembleSpans -fuzztime=60s ./internal/merge`.

// FuzzAssembleSpans assembles two pipelines whose names and contents are
// operator-supplied text and checks the span map against the bytes:
//
//   - Spans(content) recovers exactly the spans Assemble recorded, so the
//     serve path (which keeps only the bytes) attributes like the writer —
//     up to the header's rendering of a name with a line break in it.
//   - Locate maps every line of each pipeline's own text back to that
//     pipeline and line, and the served line is that pipeline line
//     (indented by two spaces, or empty for an empty line).
func FuzzAssembleSpans(f *testing.F) {
	f.Add("alpha", "prometheus.scrape \"one\" {\n  targets = []\n  forward_to = []\n}\n", 3,
		"Beta Pipe!", "// first line\n\nprometheus.scrape \"two\" {\n  targets = []\n  bogus = true\n  forward_to = []\n}", 1)
	f.Add("a", "", 0, "b", "\n\n", -1)
	f.Add("x (rev 3)", "}\npipe_x \"default\" { }", 2, "9lives", "declare \"pipe_y\" {\n}", 4)
	f.Add("line\nbreak", "a\r\nb\r\n", 1, "tab\tname", "\n}\n", 1)

	f.Fuzz(func(t *testing.T, name1, contents1 string, rev1 int, name2, contents2 string, rev2 int) {
		cl := merge.CollectorLabels{CollectorID: "c1", Labels: map[string]string{"cluster": "prod"}}
		ps := []merge.Pipeline{
			{ID: "1", Name: name1, Contents: contents1, Revision: rev1, Source: "ui", Matchers: []string{`cluster="prod"`}},
			{ID: "2", Name: name2, Contents: contents2, Revision: rev2, Source: "ui", Matchers: []string{`cluster="prod"`}},
		}
		res, err := merge.Assemble("c1", "prod/metrics", cl, ps)
		if err != nil {
			// The only refusal for these inputs is a block-name collision.
			if merge.SanitizeName(name1) != merge.SanitizeName(name2) {
				t.Fatalf("Assemble: %v", err)
			}
			return
		}
		got := merge.Spans(res.Content)
		if len(got) != len(res.Spans) {
			t.Fatalf("Spans recovered %d spans, Assemble recorded %d\n%s", len(got), len(res.Spans), res.Content)
		}
		for i := range got {
			want := res.Spans[i]
			if !strings.ContainsAny(name1+name2, "\r\n") {
				if got[i] != want {
					t.Fatalf("span %d: Spans = %+v, Assemble = %+v\n%s", i, got[i], want, res.Content)
				}
				continue
			}
			// A name the header cannot carry verbatim (a line break: the API
			// refuses one, a git-synced file path can carry one) comes back as
			// the header prints it or as the block name — never as the other
			// pipeline's name.
			name := got[i].PipelineName
			got[i].PipelineName = want.PipelineName
			if got[i] != want || (name != headerName(want.PipelineName) && name != want.BlockName) {
				t.Fatalf("span %d: Spans = %+v (name %q), Assemble = %+v\n%s", i, got[i], name, want, res.Content)
			}
		}

		served := strings.Split(res.Content, "\n")
		byName := map[string]string{name1: contents1, name2: contents2}
		for _, s := range res.Spans {
			own := strings.Split(strings.TrimSuffix(byName[s.PipelineName], "\n"), "\n")
			for k, want := range own {
				line := s.DeclareLine + 1 + k
				loc, ok := merge.Locate(res.Content, line)
				if !ok || loc.BlockName != s.BlockName || loc.PipelineLine != k+1 {
					t.Fatalf("Locate(%d) = %+v, %v; want %q line %d", line, loc, ok, s.PipelineName, k+1)
				}
				if want != "" {
					want = "  " + want
				}
				if served[line-1] != want {
					t.Fatalf("served line %d = %q, pipeline %q line %d = %q", line, served[line-1], s.PipelineName, k+1, want)
				}
			}
			for _, wrapper := range []int{s.DeclareLine, s.EndLine - 1, s.EndLine} {
				loc, ok := merge.Locate(res.Content, wrapper)
				if !ok || loc.BlockName != s.BlockName || loc.PipelineLine != 0 {
					t.Fatalf("wrapper line %d: Locate = %+v, %v; want %q with no pipeline line", wrapper, loc, ok, s.PipelineName)
				}
			}
		}
	})
}

// headerName is a pipeline name as the served header prints it (commentSafe).
func headerName(s string) string {
	return strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ").Replace(s)
}

// FuzzLocate feeds arbitrary served content and an arbitrary line — what a
// collector's load error names — to the attribution the reconcile RPC runs.
// It must never panic, and an attributed line must lie inside its span with
// a pipeline line that fits the block.
func FuzzLocate(f *testing.F) {
	f.Add("// Generated by Shepherd\n//   - a (rev 1)\n\ndeclare \"pipe_a\" {\n  x {}\n}\npipe_a \"default\" { }\n", 5)
	f.Add("declare \"pipe_a\" {\n}\npipe_a \"default\" { }", 1)
	f.Add("declare \"pipe_a\" {\n}\n", 2)
	f.Add("", 0)
	f.Add("\n\n\n", -7)

	f.Fuzz(func(t *testing.T, content string, line int) {
		loc, ok := merge.Locate(content, line)
		if !ok {
			return
		}
		if line < loc.DeclareLine || line > loc.EndLine {
			t.Fatalf("line %d attributed to span %d..%d", line, loc.DeclareLine, loc.EndLine)
		}
		if loc.PipelineLine < 0 || (loc.PipelineLine > 0 && loc.DeclareLine+loc.PipelineLine != line) {
			t.Fatalf("line %d: pipeline line %d inconsistent with declare line %d", line, loc.PipelineLine, loc.DeclareLine)
		}
		if n := strings.Count(content, "\n") + 1; loc.EndLine > n {
			t.Fatalf("span ends at line %d of a %d-line config", loc.EndLine, n)
		}
	})
}

// FuzzErrorPosition reads the line:col out of an arbitrary collector-reported
// error message: never a panic, and a position it reports is positive.
func FuzzErrorPosition(f *testing.F) {
	for _, s := range []string{
		"40:3: Failed to build component: decoding configuration",
		"remote.alloy:12:5: unrecognized attribute name \"bogus\"",
		"loading config: 7:1: expected block",
		"context deadline exceeded",
		"at 12:01:02 something failed",
		"99999999999999999999:1: overflow",
		"0:0: zero",
	} {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, msg string) {
		line, col, ok := merge.ErrorPosition(msg)
		if !ok {
			if line != 0 || col != 0 {
				t.Fatalf("not ok but returned %d:%d", line, col)
			}
			return
		}
		if line < 1 || col < 0 {
			t.Fatalf("ErrorPosition(%q) = %d:%d", msg, line, col)
		}
	})
}
