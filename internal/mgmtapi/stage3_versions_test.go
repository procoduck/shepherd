package mgmtapi_test

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/jackc/pgx/v5/pgtype"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"shepherd/internal/auth"
	"shepherd/internal/config"
	"shepherd/internal/store"
	"shepherd/internal/store/sqlc"
	"shepherd/internal/validate"
	"shepherd/internal/version"
)

// #375: Stage 3 checks each affected collector's merged config against the
// schema of every Alloy version its ACTIVE instances report. A stand-in
// alloy binary accepts everything, so any refusal here is the version check.
var _ = Describe("Stage 3 version-aware validation (#375)", Label("integration"), func() {
	const inactiveAfter = 10 * time.Minute

	var (
		ctx         context.Context
		cancel      context.CancelFunc
		st          *store.Store
		server      *httptest.Server
		org         sqlc.Org
		adminCookie *http.Cookie
		captureDir  string
	)
	pinned := validate.DisplayVersion(version.AlloySchemaVersion)

	BeforeEach(func() {
		ctx, cancel = context.WithCancel(context.Background())
		var err error
		st, err = store.New(ctx, &config.DatabaseConfig{URL: sharedPG.IsolatedDB(ctx, GinkgoTB()), MaxConns: 5})
		Expect(err).NotTo(HaveOccurred())
		org, err = st.Queries.CreateOrg(ctx, sqlc.CreateOrgParams{Name: "ver-org", DisplayName: "Versions", AdminGroupID: "admin-group"})
		Expect(err).NotTo(HaveOccurred())

		captureDir = GinkgoT().TempDir()
		fakeAlloy := filepath.Join(GinkgoT().TempDir(), "alloy")
		script := "#!/bin/sh\nfor a; do f=$a; done\n" +
			"grep -q 'Generated by Shepherd' \"$f\" || exit 0\n" +
			"cp \"$f\" \"$(mktemp " + captureDir + "/validated.XXXXXX)\"\n" +
			"exit 0\n"
		Expect(os.WriteFile(fakeAlloy, []byte(script), 0o700)).To(Succeed())

		cfg := &config.Config{
			Auth:     config.AuthConfig{InsecureCookies: true},
			Server:   config.ServerConfig{BaseURL: "https://shepherd.example.test"},
			Validate: config.ValidateConfig{AlloyBinary: fakeAlloy, StabilityLevel: "experimental", Timeout: 10e9},
			Agent:    config.AgentConfig{InactiveAfter: inactiveAfter},
		}
		authHandler := auth.NewLocalAdmin(cfg, st, slog.Default())
		server = httptest.NewServer(newRPCWiringRouter(st, authHandler, cfg))
		adminCookie = newAppAdminSession(ctx, st)
	})

	AfterEach(func() {
		server.Close()
		st.Close()
		cancel()
	})

	collector := func(cluster, role string) pgtype.UUID {
		cl, err := st.Queries.UpsertCluster(ctx, cluster)
		Expect(err).NotTo(HaveOccurred())
		Expect(st.Queries.ClaimCluster(ctx, sqlc.ClaimClusterParams{ID: cl.ID, OrgID: org.ID})).To(Succeed())
		c, err := st.Queries.UpsertCollector(ctx, sqlc.UpsertCollectorParams{ClusterID: cl.ID, Role: role})
		Expect(err).NotTo(HaveOccurred())
		return c.ID
	}
	instance := func(coll pgtype.UUID, id, alloyVersion string) {
		_, err := st.Queries.UpsertCollectorInstance(ctx, sqlc.UpsertCollectorInstanceParams{
			ID: id, CollectorID: coll, Name: id, LocalAttributes: json.RawMessage(`{}`),
			AlloyVersion: pgtype.Text{String: alloyVersion, Valid: alloyVersion != ""},
		})
		Expect(err).NotTo(HaveOccurred())
	}
	// RAW-SQL-OK: backdating last_seen makes an instance inactive — no sqlc
	// query takes an explicit last_seen, and this is a _test.go file.
	backdate := func(id string, ago time.Duration) {
		_, err := st.Pool().Exec(ctx,
			`UPDATE collector_instances SET last_seen = now() - make_interval(secs => $2) WHERE id = $1`,
			id, ago.Seconds())
		Expect(err).NotTo(HaveOccurred())
	}
	pipeline := func(name, contents string, matchers ...string) string {
		m, err := json.Marshal(matchers)
		Expect(err).NotTo(HaveOccurred())
		p, err := st.Queries.CreatePipeline(ctx, sqlc.CreatePipelineParams{
			OrgID: org.ID, Name: name, Contents: contents, Matchers: m, Enabled: false, Source: "ui",
			WizardState: json.RawMessage(`{}`), CreatedBy: "test", UpdatedBy: "test",
		})
		Expect(err).NotTo(HaveOccurred())
		return p.ID.String()
	}
	call := func(procedure string, body map[string]any) (int, string) {
		body["orgId"] = org.ID.String()
		resp := postConnectJSON(server, "/shepherd.mgmt.v1.PipelineService/"+procedure, adminCookie, body)
		var out struct{ Code, Message string }
		Expect(json.NewDecoder(resp.Body).Decode(&out)).To(Succeed())
		Expect(resp.Body.Close()).To(Succeed())
		msg := out.Message
		if out.Code != "" {
			msg = out.Code + ": " + msg
		}
		return resp.StatusCode, msg
	}
	enable := func(id string) (int, string) { return call("EnablePipeline", map[string]any{"id": id}) }
	runs := func() int {
		files, err := filepath.Glob(filepath.Join(captureDir, "validated.*"))
		Expect(err).NotTo(HaveOccurred())
		return len(files)
	}

	const redaction = `otelcol.processor.redaction "scrub" {
  allow_all_keys = true
  output {
    traces = []
  }
}
`
	const podMonitor = `prometheus.operator.podmonitors "pods" {
  forward_to = []
  scrape {
    scrape_classic_histograms = true
  }
}
`

	It("refuses otelcol.processor.redaction for a 1.18.1 collector, naming collector, version and component", func() {
		c := collector("old", "receiver")
		instance(c, "old-0", "v1.18.1")
		id := pipeline("scrub", redaction, `cluster="old"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring("old/receiver"))
		Expect(msg).To(ContainSubstring("component otelcol.processor.redaction is not available in Alloy v1.18.1"))
	})

	It("refuses scrape_classic_histograms on prometheus.operator.podmonitors for a 1.18.1 collector", func() {
		c := collector("old", "metrics")
		instance(c, "old-0", "v1.18.1")
		id := pipeline("pods", podMonitor, `cluster="old"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring("attribute scrape_classic_histograms"))
		Expect(msg).To(ContainSubstring("v1.18.1"))
	})

	It("accepts the same pipeline on a collector whose every active instance runs the pin", func() {
		c := collector("new", "metrics")
		instance(c, "new-0", pinned)
		id := pipeline("pods", podMonitor, `cluster="new"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
	})

	It("refuses a mixed-version collector for its oldest active instance", func() {
		c := collector("mixed", "metrics")
		instance(c, "mixed-0", pinned)
		instance(c, "mixed-1", "v1.20.1")
		instance(c, "mixed-2", "v1.18.1")
		id := pipeline("pods", podMonitor, `cluster="mixed"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring("v1.18.1"))
		Expect(msg).NotTo(ContainSubstring("v1.20.1"))
	})

	It("ignores an old pod that is no longer active", func() {
		c := collector("rolled", "metrics")
		instance(c, "rolled-new", pinned)
		instance(c, "rolled-old", "v1.18.1")
		backdate("rolled-old", 2*inactiveAfter)
		id := pipeline("pods", podMonitor, `cluster="rolled"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
	})

	It("saves, falling back to the pinned schema, for a version newer than every shipped schema", func() {
		c := collector("future", "metrics")
		instance(c, "future-0", "v9.0.0")
		id := pipeline("pods", podMonitor, `cluster="future"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
	})

	It("checks a version without its own schema against the nearest older one", func() {
		c := collector("patch", "metrics")
		instance(c, "patch-0", "v1.18.5")
		id := pipeline("pods", podMonitor, `cluster="patch"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring("not available in Alloy v1.18.1"))
		Expect(msg).To(ContainSubstring("[reported by patch-0 (v1.18.5)]"), "the refusal names the instance behind it")
	})

	It("names the instances reporting a refused version, capped and sanitised", func() {
		c := collector("crowd", "metrics")
		for i := range 5 {
			instance(c, fmt.Sprintf("old-%d", i), "v1.18.1")
		}
		instance(c, "new-0", pinned)
		id := pipeline("pods", podMonitor, `cluster="crowd"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(MatchRegexp(`\[reported by old-\d \(v1\.18\.1\), old-\d \(v1\.18\.1\), old-\d \(v1\.18\.1\) and 2 more\]`))
		Expect(msg).NotTo(ContainSubstring("new-0"))
	})

	// RAW-SQL-OK: bulk-inserting agent-chosen versions — thousands of
	// UpsertCollectorInstance calls would dominate the spec; _test.go file.
	junk := func(coll pgtype.UUID, prefix string, n int) {
		_, err := st.Pool().Exec(ctx,
			`INSERT INTO collector_instances (id, collector_id, name, local_attributes, alloy_version, last_seen)
			 SELECT $2 || g, $1, $2 || g, '{}', 'v9.' || g || '.0', now() FROM generate_series(1, $3::int) g`,
			coll, prefix, n)
		Expect(err).NotTo(HaveOccurred())
	}

	It("still refuses for an old version on a collector sorting after one flooded with versions (#409 re-review)", func() {
		a := collector("flood-a", "metrics")
		b := collector("flood-b", "metrics")
		// The flood goes on whichever collector sorts first, so the old
		// version's collector is the one an org-wide row cut would drop.
		flooded, victim, victimCluster := a, b, "flood-b"
		if b.String() < a.String() {
			flooded, victim, victimCluster = b, a, "flood-a"
		}
		junk(flooded, "junk-", 4200)
		instance(victim, "old-0", "v1.18.1")
		id := pipeline("pods", podMonitor, `cluster="`+victimCluster+`"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring(victimCluster + "/metrics"))
		Expect(msg).To(ContainSubstring("not available in Alloy v1.18.1"))
	})

	It("checks a collector whose versions were capped against the oldest shipped schema", func() {
		c := collector("capped", "metrics")
		junk(c, "junk-", 300) // all too new: alone they resolve to the pin
		id := pipeline("pods", podMonitor, `cluster="capped"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(msg).To(ContainSubstring("not available in Alloy v1.18.1"),
			"truncated version data never falls back to the pin")
	})

	Describe("a mismatch the collector is already served (only new failures refuse)", func() {
		var served, other string
		BeforeEach(func() {
			c := collector("old", "metrics")
			instance(c, "new-0", pinned)
			// Served before the old pod joined.
			served = pipeline("pods", podMonitor, `cluster="old"`)
			status, msg := enable(served)
			Expect(status).To(Equal(http.StatusOK), msg)
			other = pipeline("other", "prometheus.exporter.self \"self\" { }\n", `cluster="old"`)
			status, msg = enable(other)
			Expect(status).To(Equal(http.StatusOK), msg)
			instance(c, "old-0", "v1.18.1")
		})

		It("does not refuse disabling an unrelated pipeline", func() {
			status, msg := call("DisablePipeline", map[string]any{"id": other})
			Expect(status).To(Equal(http.StatusOK), msg)
		})

		It("does not refuse disabling the mismatched pipeline itself", func() {
			status, msg := call("DisablePipeline", map[string]any{"id": served})
			Expect(status).To(Equal(http.StatusOK), msg)
		})

		It("does not refuse an edit of an unrelated pipeline", func() {
			status, msg := call("UpdatePipeline", map[string]any{
				"id": other, "name": "other", "contents": "prometheus.exporter.self \"self2\" { }\n",
				"matchers": []string{`cluster="old"`},
			})
			Expect(status).To(Equal(http.StatusOK), msg)
		})

		It("still refuses an edit of the mismatched pipeline that keeps the item", func() {
			status, msg := call("UpdatePipeline", map[string]any{
				"id": served, "name": "pods", "contents": "// edited\n" + podMonitor, "matchers": []string{`cluster="old"`},
			})
			Expect(status).To(Equal(http.StatusBadRequest), msg)
			Expect(msg).To(ContainSubstring("scrape_classic_histograms"))
		})

		It("still refuses an edit of the mismatched pipeline that leaves the failing line where it was", func() {
			status, msg := call("UpdatePipeline", map[string]any{
				"id": served, "name": "pods", "contents": podMonitor + "// edited\n", "matchers": []string{`cluster="old"`},
			})
			Expect(status).To(Equal(http.StatusBadRequest), msg)
			Expect(msg).To(ContainSubstring("scrape_classic_histograms"))
		})

		It("still refuses a new pipeline bringing a new failure", func() {
			id := pipeline("scrub2", strings.ReplaceAll(podMonitor, `"pods"`, `"pods2"`), `cluster="old"`)
			status, msg := enable(id)
			Expect(status).To(Equal(http.StatusBadRequest), msg)
			Expect(msg).To(ContainSubstring(`podmonitors "pods2"`))
			Expect(msg).NotTo(ContainSubstring(`podmonitors "pods" `))
		})
	})

	It("keys the dedupe by content and version set: one alloy validate, one verdict per version set", func() {
		for i := range 3 {
			c := collector(fmt.Sprintf("v18-%d", i), "metrics")
			instance(c, fmt.Sprintf("v18-%d-0", i), "v1.18.1")
		}
		for i := range 2 {
			c := collector(fmt.Sprintf("pin-%d", i), "metrics")
			instance(c, fmt.Sprintf("pin-%d-0", i), pinned)
		}
		id := pipeline("pods", podMonitor, `role="metrics"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusBadRequest), msg)
		Expect(runs()).To(Equal(1), "five collectors with identical bytes still cost one alloy validate")
		// The three 1.18.1 collectors share one verdict line; the pinned
		// ones are not refused.
		Expect(msg).To(ContainSubstring("v18-0/metrics, v18-1/metrics, v18-2/metrics: version:"))
		Expect(strings.Count(msg, "scrape_classic_histograms")).To(Equal(1))
		Expect(msg).NotTo(ContainSubstring("pin-0"))
	})

	It("presents the recorded serve-time warning on ListCollectors and GetCollector", func() {
		c := collector("flagged", "metrics")
		instance(c, "flagged-0", "v1.18.1")
		_, err := st.Queries.SetCollectorVersionWarning(ctx, sqlc.SetCollectorVersionWarningParams{
			ID: c, Mismatch: true,
			Warning: pgtype.Text{String: "line 4: attribute x is not available in Alloy v1.18.1\nruns Alloy 1.17.0, which no shipped schema covers", Valid: true},
		})
		Expect(err).NotTo(HaveOccurred())

		type warning struct {
			Findings []string `json:"findings"`
			Mismatch bool     `json:"mismatch"`
			Since    string   `json:"since"`
		}
		resp := postConnectJSON(server, "/shepherd.mgmt.v1.FleetService/GetCollector", adminCookie,
			map[string]any{"orgId": org.ID.String(), "id": c.String()})
		var got struct {
			VersionWarning *warning `json:"versionWarning"`
		}
		Expect(json.NewDecoder(resp.Body).Decode(&got)).To(Succeed())
		Expect(resp.Body.Close()).To(Succeed())
		Expect(got.VersionWarning).NotTo(BeNil())
		Expect(got.VersionWarning.Findings).To(HaveLen(2))
		Expect(got.VersionWarning.Mismatch).To(BeTrue())
		Expect(got.VersionWarning.Since).NotTo(BeEmpty())

		resp = postConnectJSON(server, "/shepherd.mgmt.v1.FleetService/ListCollectors", adminCookie,
			map[string]any{"orgId": org.ID.String()})
		var list struct {
			Items []struct {
				VersionWarning *warning `json:"versionWarning"`
			} `json:"items"`
		}
		Expect(json.NewDecoder(resp.Body).Decode(&list)).To(Succeed())
		Expect(resp.Body.Close()).To(Succeed())
		Expect(list.Items).To(HaveLen(1))
		Expect(list.Items[0].VersionWarning).NotTo(BeNil())
		Expect(list.Items[0].VersionWarning.Mismatch).To(BeTrue())
	})

	It("reports the org's versions to the author as ValidatePipeline warnings", func() {
		c := collector("old", "metrics")
		instance(c, "old-0", "v1.18.1")
		resp := postConnectJSON(server, "/shepherd.mgmt.v1.PipelineService/ValidatePipeline", adminCookie,
			map[string]any{"orgId": org.ID.String(), "name": "pods", "contents": podMonitor})
		var out struct {
			Valid       bool `json:"valid"`
			Diagnostics []struct {
				Message string `json:"message"`
				Warning bool   `json:"warning"`
				Line    int    `json:"line"`
			} `json:"diagnostics"`
		}
		Expect(json.NewDecoder(resp.Body).Decode(&out)).To(Succeed())
		Expect(resp.Body.Close()).To(Succeed())
		Expect(out.Valid).To(BeTrue(), "version findings never fail ValidatePipeline")
		Expect(out.Diagnostics).To(ContainElement(SatisfyAll(
			HaveField("Warning", BeTrue()),
			HaveField("Line", Equal(4)),
			HaveField("Message", ContainSubstring("scrape_classic_histograms (in prometheus.operator.podmonitors \"pods\" > scrape) is not available in Alloy v1.18.1")),
		)))
	})
})
