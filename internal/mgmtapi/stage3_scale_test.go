// Review step 4d (#376): Stage 3 validates only the collectors a change can
// affect — those the candidate's old or new matchers select — and runs
// `alloy validate` once per distinct merged config, with the collector id
// (header comment, D6 baseline's shepherd_collector_id literal) normalised
// out. A stand-in alloy binary records every merged config it is handed and
// fails the ones carrying a marker, so each spec can count runs and check the
// verdict.
//
// Red run, executed: before the fix every enable validated every collector in
// the org once each (the per-collector id defeated the hash de-duplication),
// so the "exactly one run" assertions saw one run per collector.
var _ = Describe("Stage 3 scale (#376)", Label("integration"), func() {
	var (
		ctx         context.Context
		cancel      context.CancelFunc
		st          *store.Store
		server      *httptest.Server
		org         sqlc.Org
		adminCookie *http.Cookie
		captureDir  string
	)

	BeforeEach(func() {
		ctx, cancel = context.WithCancel(context.Background())
		var err error
		st, err = store.New(ctx, &config.DatabaseConfig{URL: sharedPG.IsolatedDB(ctx, GinkgoTB()), MaxConns: 5})
		Expect(err).NotTo(HaveOccurred())

		org, err = st.Queries.CreateOrg(ctx, sqlc.CreateOrgParams{Name: "scale-org", DisplayName: "Scale Org", AdminGroupID: "admin-group"})
		Expect(err).NotTo(HaveOccurred())

		// Records only merged configs (the "Generated by Shepherd" header):
		// CreatePipeline/UpdatePipeline also run Stage 2 on the bare pipeline,
		// which is not what these specs count. Fails a merged config that
		// carries BREAK_ME, or both halves of the conflict pair.
		captureDir = GinkgoT().TempDir()
		fakeAlloy := filepath.Join(GinkgoT().TempDir(), "alloy")
		script := "#!/bin/sh\nfor a; do f=$a; done\n" +
			"grep -q 'Generated by Shepherd' \"$f\" || exit 0\n" +
			"cp \"$f\" \"$(mktemp " + captureDir + "/validated.XXXXXX)\"\n" +
			"if grep -q BREAK_ME \"$f\"; then echo \"$f:1:1: broken by BREAK_ME\" >&2; exit 1; fi\n" +
			"if grep -q conflict-a \"$f\" && grep -q conflict-b \"$f\"; then echo \"$f:1:1: conflict-a clashes with conflict-b\" >&2; exit 1; fi\n" +
			"exit 0\n"
		Expect(os.WriteFile(fakeAlloy, []byte(script), 0o700)).To(Succeed())

		cfg := &config.Config{
			Auth:     config.AuthConfig{InsecureCookies: true},
			Server:   config.ServerConfig{BaseURL: "https://shepherd.example.test"},
			Validate: config.ValidateConfig{AlloyBinary: fakeAlloy, StabilityLevel: "experimental", Timeout: 10e9},
		}
		authHandler := auth.NewLocalAdmin(cfg, st, slog.Default())
		server = httptest.NewServer(newRPCWiringRouter(st, authHandler, cfg))
		adminCookie = newAppAdminSession(ctx, st)
	})

	AfterEach(func() {
		server.Close()
		st.Close()
		cancel()
	})

	// collector creates cluster/role, claimed by the org, and returns its id.
	collector := func(cluster, role string) pgtype.UUID {
		cl, err := st.Queries.UpsertCluster(ctx, cluster)
		Expect(err).NotTo(HaveOccurred())
		Expect(st.Queries.ClaimCluster(ctx, sqlc.ClaimClusterParams{ID: cl.ID, OrgID: org.ID})).To(Succeed())
		c, err := st.Queries.UpsertCollector(ctx, sqlc.UpsertCollectorParams{ClusterID: cl.ID, Role: role})
		Expect(err).NotTo(HaveOccurred())
		return c.ID
	}
	fleet := func(n int, roles ...string) {
		for i := range n {
			for _, r := range roles {
				collector(fmt.Sprintf("c%d", i), r)
			}
		}
	}
	// pipeline inserts a pipeline row directly (no Stage 3), enabled or not.
	pipeline := func(name, contents string, enabled bool, matchers ...string) string {
		m, err := json.Marshal(matchers)
		Expect(err).NotTo(HaveOccurred())
		p, err := st.Queries.CreatePipeline(ctx, sqlc.CreatePipelineParams{
			OrgID: org.ID, Name: name, Contents: contents, Matchers: m, Enabled: enabled, Source: "ui",
			WizardState: json.RawMessage(`{}`), CreatedBy: "test", UpdatedBy: "test",
		})
		Expect(err).NotTo(HaveOccurred())
		return p.ID.String()
	}
	runs := func() []string {
		files, err := filepath.Glob(filepath.Join(captureDir, "validated.*"))
		Expect(err).NotTo(HaveOccurred())
		var out []string
		for _, f := range files {
			b, err := os.ReadFile(f)
			Expect(err).NotTo(HaveOccurred())
			out = append(out, string(b))
		}
		return out
	}
	resetRuns := func() {
		files, err := filepath.Glob(filepath.Join(captureDir, "validated.*"))
		Expect(err).NotTo(HaveOccurred())
		for _, f := range files {
			Expect(os.Remove(f)).To(Succeed())
		}
	}
	call := func(procedure string, body map[string]any) (int, string) {
		body["orgId"] = org.ID.String()
		resp := postConnectJSON(server, "/shepherd.mgmt.v1.PipelineService/"+procedure, adminCookie, body)
		var out struct{ Code, Message string }
		Expect(json.NewDecoder(resp.Body).Decode(&out)).To(Succeed())
		Expect(resp.Body.Close()).To(Succeed())
		msg := out.Message
		if out.Code != "" {
			msg = out.Code + ": " + msg
		}
		return resp.StatusCode, msg
	}
	enable := func(id string) (int, string) { return call("EnablePipeline", map[string]any{"id": id}) }

	It("validates only the one collector a cluster matcher selects", func() {
		fleet(6, "metrics")
		id := pipeline("one-cluster", "// one-cluster", false, `cluster="c2"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
		got := runs()
		Expect(got).To(HaveLen(1), "Stage 3 validated collectors the pipeline does not select")
		Expect(got[0]).To(ContainSubstring("one-cluster"))
	})

	It("validates only the collector a cluster AND role matcher selects", func() {
		fleet(3, "metrics", "logs")
		id := pipeline("one-role", "// one-role", false, `cluster="c1"`, `role="logs"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
		Expect(runs()).To(HaveLen(1))
	})

	It("runs alloy validate once for collectors whose merged configs differ only by id", func() {
		fleet(6, "metrics")
		id := pipeline("every-metrics", "// every-metrics", false, `role="metrics"`)

		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
		got := runs()
		Expect(got).To(HaveLen(1), "six identical merged configs must cost one alloy validate")
		Expect(got[0]).To(ContainSubstring("every-metrics"))
		Expect(got[0]).To(ContainSubstring("shepherd_collector_id"),
			"the validated bytes keep the baseline's collector-id rule, with a placeholder value")
	})

	It("selects by admin labels only when the org allows label matching", func() {
		fleet(5, "metrics")
		coll := collector("c3", "metrics")
		_, err := st.Queries.SetCollectorLabel(ctx, sqlc.SetCollectorLabelParams{ID: coll, LabelKey: "team", LabelValue: "payments"})
		Expect(err).NotTo(HaveOccurred())
		id := pipeline("by-label", "// by-label", false, `team="payments"`)

		// Flag off: the label is not matched by the serve path, so the
		// pipeline affects no collector and nothing is validated.
		status, msg := enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
		Expect(runs()).To(BeEmpty())
		status, msg = call("DisablePipeline", map[string]any{"id": id})
		Expect(status).To(Equal(http.StatusOK), msg)
		resetRuns()

		_, err = st.Queries.UpdateOrg(ctx, sqlc.UpdateOrgParams{
			ID: org.ID, DisplayName: org.DisplayName, AdminGroupID: org.AdminGroupID, ReaderGroupID: org.ReaderGroupID,
			AllowLabelMatching: true,
		})
		Expect(err).NotTo(HaveOccurred())
		status, msg = enable(id)
		Expect(status).To(Equal(http.StatusOK), msg)
		got := runs()
		Expect(got).To(HaveLen(1))
		Expect(got[0]).To(ContainSubstring("by-label"))
	})

	It("validates the old matchers' collectors too, on update and on disable", func() {
		fleet(5, "metrics")
		id := pipeline("moving", "// moving", true, `cluster="c1"`)

		status, msg := call("UpdatePipeline", map[string]any{
			"id": id, "name": "moving", "contents": "// moving", "matchers": []string{`cluster="c2"`},
		})
		Expect(status).To(Equal(http.StatusOK), msg)
		got := runs()
		Expect(got).To(HaveLen(2), "c1 (losing the pipeline) and c2 (gaining it)")
		Expect(strings.Join(got, "\n")).To(ContainSubstring("No pipelines matched"))

		resetRuns()
		status, msg = call("DisablePipeline", map[string]any{"id": id})
		Expect(status).To(Equal(http.StatusOK), msg)
		Expect(runs()).To(HaveLen(1), "only c2, the collector the disabled pipeline leaves")
	})

	It("still refuses a candidate that newly matches a collector with a conflicting pipeline", func() {
		fleet(4, "metrics")
		pipeline("existing", "// conflict-a", true, `cluster="c0"`)
		id := pipeline("candidate", "// conflict-b", true, `cluster="c1"`)

		status, msg := call("UpdatePipeline", map[string]any{
			"id": id, "name": "candidate", "contents": "// conflict-b", "matchers": []string{`cluster=~"c0|c1"`},
		})
		Expect(status).NotTo(Equal(http.StatusOK))
		Expect(msg).To(HavePrefix("failed_precondition: "))
		Expect(msg).To(ContainSubstring("c0/metrics"))
		Expect(msg).To(ContainSubstring("conflict-a clashes with conflict-b"))
		Expect(msg).NotTo(ContainSubstring("c1/metrics"), "c1's merged config is valid")
	})

	It("attributes a failure to every collector that shares the failing config", func() {
		fleet(4, "metrics")
		collector("c0", "logs")
		id := pipeline("broken", "// BREAK_ME", false, `role="metrics"`)

		status, msg := enable(id)
		Expect(status).NotTo(Equal(http.StatusOK))
		Expect(msg).To(HavePrefix("failed_precondition: "))
		Expect(runs()).To(HaveLen(1))
		for i := range 4 {
			Expect(msg).To(ContainSubstring(fmt.Sprintf("c%d/metrics", i)))
		}
		Expect(msg).To(ContainSubstring("broken by BREAK_ME"))
		Expect(msg).NotTo(ContainSubstring("c0/logs"))
	})
})
