// scrapePipeline is a minimal, individually-valid-Alloy fixture pipeline —
// ComputeServed always Stage-1-validates the FINAL merged content (see
// TestComputeServed_UnparsableNeverServed), so every fixture used for a
// success-path assertion must itself be syntactically valid.
func scrapePipeline(id, name string, matchers []string) merge.Pipeline {
	return merge.Pipeline{
		ID:   id,
		Name: name,
		Contents: `prometheus.scrape "a" {
  targets    = []
  forward_to = []
}`,
		Matchers: matchers,
		Source:   "ui",
	}
}

// TestComputeServed_Golden proves ComputeServed's output for a fixed input is
// exactly what the two former call sites (agentapi.recomputeServeCache,
// mgmtapi.recomputeOrgCaches) used to build by hand: merge.Assemble's
// declare-wrapped content, byte-identical (the header carries no
// generation timestamp since #213), with Hash always matching
// HashContent(Content).
//
// The fixture carries Revision 3 so the golden pins "(rev 3)": the served
// header prints each pipeline's current revision (#296 — it read "(rev 0)"
// for every pipeline before, because no caller set Revision). These bytes
// feed the hash every collector compares on each poll; a change here means
// every matched collector reloads once, so they are pinned on purpose.
// #308: the first line is "// Generated by Shepherd" — it read
// "// Generated by Shepherd prod" for every deployment, a hard-coded label
// that named no real environment (serve.Format 2 recomputes cached rows).
func TestComputeServed_Golden(t *testing.T) {
	p := scrapePipeline("p1", "alpha", []string{`cluster="c1"`})
	p.Revision = 3
	pipelines := []merge.Pipeline{p}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}

	got, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, pipelines)
	if err != nil {
		t.Fatalf("ComputeServed: %v", err)
	}

	const want = `// Generated by Shepherd
// Collector: c1/metrics (coll-1)
// Pipelines (1):
//   - alpha (rev 3)

declare "pipe_alpha" {
  prometheus.scrape "a" {
    targets    = []
    forward_to = []
  }
}
pipe_alpha "default" { }
`
	if got := got.Content; got != want {
		t.Fatalf("content mismatch:\n got:\n%s\nwant:\n%s", got, want)
	}
	if want := merge.HashContent(got.Content); got.Hash != want {
		t.Fatalf("Hash %q does not match HashContent(Content) %q", got.Hash, want)
	}
	if len(got.Exclusions) != 0 {
		t.Fatalf("unexpected exclusions: %+v", got.Exclusions)
	}
	if got.BaselineErr != nil {
		t.Fatalf("unexpected BaselineErr: %v", got.BaselineErr)
	}
}

// TestComputeServed_BaselineChangesHash proves the specific line both former
// call sites carried verbatim — "if content changed after appending the
// baseline, recompute the hash from the NEW content, not the merge-only one"
// — survived the extraction. Getting this wrong (serving merge.Assemble's
// original Hash after the baseline mutated Content) was exactly the kind of
// two-path drift docs/gateway-tier-plan.md §10 warns about.
func TestComputeServed_BaselineChangesHash(t *testing.T) {
	pipelines := []merge.Pipeline{scrapePipeline("p1", "alpha", []string{`cluster="c1"`})}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}

	without, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, pipelines)
	if err != nil {
		t.Fatalf("ComputeServed (no baseline): %v", err)
	}

	deps := serve.Deps{Schema: mustSchema(t), BeaconBaseline: beacon.NewBaselineConfig("https://shepherd.example.test" + beacon.WritePath)}
	with, err := serve.ComputeServed(context.Background(), deps, coll, pipelines)
	if err != nil {
		t.Fatalf("ComputeServed (with baseline): %v", err)
	}

	if with.Content == without.Content {
		t.Fatalf("baseline pipeline was not appended to Content")
	}
	if with.Hash == without.Hash {
		t.Fatalf("baseline-mutated content unexpectedly kept the no-baseline hash")
	}
	if want := merge.HashContent(with.Content); with.Hash != want {
		t.Fatalf("Hash %q does not match HashContent(Content) %q after baseline append", with.Hash, want)
	}
}

// TestComputeServed_RecomputeOfUnchangedInputIsStable is the
// procoduck/shepherd#213 proof: recomputing an unchanged collector + pipeline
// set must produce byte-identical content and therefore the identical hash,
// even across a wall-clock change. Served content used to carry a
// "// Generated by Shepherd <env> at <RFC3339 now>" header line, so every
// recompute (any dirty mark — a label edit, say) changed every affected
// collector's hash and the whole fleet re-fetched and reloaded for nothing.
// The second call deliberately lands in a later wall-clock second, the
// header's former resolution, so a reintroduced timestamp fails this spec.
func TestComputeServed_RecomputeOfUnchangedInputIsStable(t *testing.T) {
	pipelines := []merge.Pipeline{scrapePipeline("p1", "alpha", []string{`cluster="c1"`})}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}
	deps := serve.Deps{Schema: mustSchema(t), BeaconBaseline: beacon.NewBaselineConfig("https://shepherd.example.test" + beacon.WritePath)}

	first, err := serve.ComputeServed(context.Background(), deps, coll, pipelines)
	if err != nil {
		t.Fatalf("first ComputeServed: %v", err)
	}
	// Sleep past the next whole-second boundary.
	now := time.Now()
	time.Sleep(now.Truncate(time.Second).Add(time.Second + 50*time.Millisecond).Sub(now))
	second, err := serve.ComputeServed(context.Background(), deps, coll, pipelines)
	if err != nil {
		t.Fatalf("second ComputeServed: %v", err)
	}

	if first.Content != second.Content {
		t.Fatalf("recompute of an unchanged config changed the served bytes:\nfirst:\n%s\nsecond:\n%s", first.Content, second.Content)
	}
	if first.Hash != second.Hash {
		t.Fatalf("recompute of an unchanged config changed the hash: %s -> %s", first.Hash, second.Hash)
	}
	if want := merge.HashContent(second.Content); second.Hash != want {
		t.Fatalf("Hash %q does not match HashContent(Content) %q", second.Hash, want)
	}
}

// TestComputeServed_ContentChangeChangesHash is #213's other half: removing
// the timestamp must not make the hash insensitive to real changes — a
// changed pipeline body, or a newly matching pipeline, still moves it.
func TestComputeServed_ContentChangeChangesHash(t *testing.T) {
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}
	base := []merge.Pipeline{scrapePipeline("p1", "alpha", []string{`cluster="c1"`})}

	before, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, base)
	if err != nil {
		t.Fatalf("ComputeServed (before): %v", err)
	}

	edited := []merge.Pipeline{scrapePipeline("p1", "alpha", []string{`cluster="c1"`})}
	edited[0].Contents = strings.Replace(edited[0].Contents, `"a"`, `"b"`, 1)
	afterEdit, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, edited)
	if err != nil {
		t.Fatalf("ComputeServed (edited): %v", err)
	}
	if afterEdit.Hash == before.Hash {
		t.Fatal("editing a pipeline body did not change the served hash")
	}

	added := []merge.Pipeline{base[0], scrapePipeline("p2", "beta", []string{`cluster="c1"`})}
	afterAdd, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, added)
	if err != nil {
		t.Fatalf("ComputeServed (added): %v", err)
	}
	if afterAdd.Hash == before.Hash || afterAdd.Hash == afterEdit.Hash {
		t.Fatal("a newly matching pipeline did not change the served hash")
	}
}

// TestComputeServed_UnparsableNeverServed: a pipeline that does not parse
// never reaches served content. With role enforcement always on (R5, #358) the
// first line of defence is enforcement itself — a pipeline whose signals cannot
// be derived is excluded fail-safe and named in the header — and Stage 1 on the
// final content stays the backstop ComputeServed runs unconditionally.
func TestComputeServed_UnparsableNeverServed(t *testing.T) {
	broken := merge.Pipeline{
		ID: "p1", Name: "broken", Contents: `prometheus.scrape "a" {`,
		Matchers: []string{`cluster="c1"`}, Source: "ui",
	}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}

	got, err := serve.ComputeServed(context.Background(), serve.Deps{Schema: mustSchema(t)}, coll, []merge.Pipeline{broken})
	if err != nil {
		return // refused outright: never served
	}
	if strings.Contains(got.Content, broken.Contents) {
		t.Fatalf("an unparsable pipeline reached served content:\n%s", got.Content)
	}
	if len(got.Exclusions) != 1 || got.Exclusions[0].PipelineName != "broken" {
		t.Fatalf("expected the unparsable pipeline to be excluded fail-safe, got exclusions %+v", got.Exclusions)
	}
}

// TestComputeServed_NilSchemaRefuses pins R5 (#358): role enforcement is
// always on, so a nil registry is a programming error that refuses to compute
// rather than serving config that looks enforced and is not. internal/server
// loads the registry once at boot and fails to start without it.
func TestComputeServed_NilSchemaRefuses(t *testing.T) {
	pipelines := []merge.Pipeline{scrapePipeline("p1", "alpha", []string{`cluster="c1"`})}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "metrics"}

	if _, err := serve.ComputeServed(context.Background(), serve.Deps{}, coll, pipelines); err == nil {
		t.Fatal("ComputeServed with a nil Schema must refuse, got nil error")
	}
	if _, err := serve.Assemble(serve.Deps{}, coll, pipelines); err == nil {
		t.Fatal("Assemble with a nil Schema must refuse, got nil error")
	}
}

// TestAssemble_IsComputeServedWithoutStage1 pins that Stage 3's dry run
// (internal/mgmtapi.stage3CheckSet, which calls Assemble) sees the exact bytes
// ComputeServed serves — D6's baseline included.
func TestAssemble_IsComputeServedWithoutStage1(t *testing.T) {
	pipelines := []merge.Pipeline{
		scrapePipeline("p1", "alpha", []string{`cluster="parity-cluster"`}),
		scrapePipeline("p2", "beta", []string{`cluster="parity-cluster"`}),
	}
	deps := serve.Deps{Schema: mustSchema(t), BeaconBaseline: beacon.NewBaselineConfig("https://shepherd.example.test" + beacon.WritePath)}
	coll := serve.Collector{ID: "coll-parity", Cluster: "parity-cluster", Role: "metrics"}

	served, err := serve.ComputeServed(context.Background(), deps, coll, pipelines)
	if err != nil {
		t.Fatalf("ComputeServed: %v", err)
	}
	assembled, err := serve.Assemble(deps, coll, pipelines)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if served.Content != assembled.Content || served.Hash != assembled.Hash {
		t.Fatalf("Assemble diverged from ComputeServed:\nserved:\n%s\nassembled:\n%s", served.Content, assembled.Content)
	}
	if !strings.Contains(assembled.Content, beacon.WritePath) {
		t.Fatalf("Assemble output lacks the D6 baseline:\n%s", assembled.Content)
	}
}

// mustSchema loads the embedded schema registry every production serve path
// is given.
func mustSchema(t *testing.T) *schema.Registry {
	t.Helper()
	reg, err := schema.New(schema.Embedded, version.AlloySchemaVersion)
	if err != nil {
		t.Fatalf("schema.New: %v", err)
	}
	return reg
}

// TestComputeServed_WizardTextSingleBlankLines is #308 end to end: real
// wizard output (a committed golden) served beside another pipeline and the
// D6 baseline, and the baseline alone for a collector nothing matched, is
// spaced by single blank lines. Red run, executed: each declare block carried
// a blank line before its closing brace (the wizard text's final newline),
// and the nothing-matched config read "// No pipelines matched\n\n\n".
func TestComputeServed_WizardTextSingleBlankLines(t *testing.T) {
	golden, err := os.ReadFile("../wizard/podlogs/testdata/json-format.golden.alloy")
	if err != nil {
		t.Fatal(err)
	}
	coll := serve.Collector{ID: "coll-1", Cluster: "c1", Role: "logs"}
	deps := serve.Deps{Schema: mustSchema(t), BeaconBaseline: beacon.NewBaselineConfig("https://shepherd.example.test" + beacon.WritePath)}
	wiz := merge.Pipeline{ID: "w", Name: "pod-logs", Contents: string(golden), Matchers: []string{`cluster="c1"`}, Source: "wizard"}
	cases := map[string][]merge.Pipeline{
		"wizard pipeline beside another": {wiz, scrapePipeline("p1", "alpha", []string{`cluster="c1"`})},
		"nothing matched":                nil,
	}
	for name, pipelines := range cases {
		got, err := serve.ComputeServed(context.Background(), deps, coll, pipelines)
		if err != nil {
			t.Fatalf("%s: ComputeServed: %v", name, err)
		}
		if strings.Contains(got.Content, "\n\n\n") {
			t.Errorf("%s: served text has a double blank line:\n%s", name, got.Content)
		}
		if strings.Contains(got.Content, "\n\n}\n") {
			t.Errorf("%s: a declare block ends in a blank line:\n%s", name, got.Content)
		}
	}
}
